"""예시 데이터 — 원본 아티팩트와 같은 값."""
from . import services

SAMPLE = [
    ("2026-Q1", "서울", 412000000, 15200), ("2026-Q2", "서울", 438500000, 15900),
    ("2026-Q3", "서울", 471200000, 16800), ("2026-Q4", "서울", 455800000, 16300),
    ("2026-Q1", "대전", 186400000, 7900), ("2026-Q2", "대전", 192700000, 8100),
    ("2026-Q3", "대전", 214300000, 8700), ("2026-Q4", "대전", 221600000, 8800),
    ("2026-Q1", "부산", 268900000, 10400), ("2026-Q2", "부산", 259300000, 10100),
    ("2026-Q3", "부산", 287600000, 10900), ("2026-Q4", "부산", 301200000, 11300),
]


def seed(db):
    """예시 데이터를 is_sample=1로 넣는다. 같은 분기·지점이 있으면 값을 덮어쓴다."""
    with db:
        for q, b, amt, cust in SAMPLE:
            services.upsert(
                db, {"quarter": q, "branch": b, "amount": amt, "customers": cust}, is_sample=1
            )
    return len(SAMPLE)
