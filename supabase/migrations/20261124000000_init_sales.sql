-- 매출 분석 테이블 (Postgres / Supabase). 로컬 SQLite용 app/schema.sql과 같은 구조.
-- 시각 컬럼은 SQLite와 같게 'YYYY-MM-DD HH24:MI:SS' 문자열(한국 시간)로 저장한다.

create table public.branches (
  id          bigint generated by default as identity primary key,
  name        text    not null unique check (char_length(name) between 1 and 30),
  color_index integer not null check (color_index between 0 and 7),
  created_at  text    not null default to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD HH24:MI:SS')
);

create table public.sales (
  id         bigint generated by default as identity primary key,
  quarter    text    not null check (quarter ~ '^[0-9]{4}-Q[1-4]$'),
  branch_id  bigint  not null references public.branches(id) on delete cascade,
  amount     bigint  not null check (amount >= 0),
  customers  bigint  not null check (customers >= 1),
  is_sample  integer not null default 0 check (is_sample in (0, 1)),
  created_at text    not null default to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD HH24:MI:SS'),
  updated_at text    not null default to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD HH24:MI:SS'),
  unique (quarter, branch_id)
);

create index idx_sales_quarter on public.sales(quarter);
create index idx_sales_branch  on public.sales(branch_id);

create table public.snapshots (
  id         bigint generated by default as identity primary key,
  action     text not null,
  payload    text not null,
  created_at text not null default to_char(now() at time zone 'Asia/Seoul', 'YYYY-MM-DD HH24:MI:SS')
);

-- 앱은 Postgres에 직접 접속(소유자 권한)한다.
-- Supabase 공개 REST API(anon 키)로는 읽기·쓰기가 되지 않도록 RLS를 켜고 정책은 두지 않는다.
alter table public.branches  enable row level security;
alter table public.sales     enable row level security;
alter table public.snapshots enable row level security;
